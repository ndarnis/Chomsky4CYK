int main (int argc, char* argv[])
{
    FILE* input_file = NULL;
    FILE* output_file = NULL;
    
    /* 1. Reading command-line options */
    {
	int opt;
	int option_index = 0;
	
	static struct option long_options[] = 
	{
	    { "input-file",  required_argument, 0, 'i' },
	    { "output-file", required_argument, 0, 'o' },
	    { "verbose",     no_argument,       0, 'v' },
	    { "version",     no_argument,       0,  0 },
	    { "help",        no_argument,       0, 'h' },
	    { 0,             0,                 0,  0 }
	};
	
	while ((opt = getopt_long (argc, argv, "i:o:vh", long_options, &option_index)) != -1)
	{
	    if (opt == 0)
	    {
		/* long option without short equivalent */
		if (strcmp (long_options[option_index].name, "version") == 0)
		{
		    version ();
		    exit (EXIT_SUCCESS);
		}
		continue;
	    }
	    
	    switch (opt)
	    {
	    case 0:
		break;
				
	    case 'i': /* input-file */
		if (!optarg)
		{
		    usage ();
		    exit (EXIT_FAILURE);
		}
		
		input_file = fopen (optarg, "r");
	
		if (!input_file)
		{
		    printf ("Unable to open file %s.\n", optarg);
		    exit (EXIT_FAILURE);
		}
		break;

				
	    case 'o': /* output-file */
		if (!optarg)
		{
		    usage ();
		    exit (EXIT_FAILURE);
		}
		
		output_file = fopen (optarg, "w+");
		break;

	    case 'h': /* help */
		usage ();
		exit (EXIT_SUCCESS);
		break;
		
	    case 'v': /* verbose */
		verbose = true;
		break;

	    default:
		exit (EXIT_FAILURE);
	    }
	}
    }

    if (input_file == NULL)
    {
	usage ();
	exit (EXIT_FAILURE);
    }

    /* Making-of lists */
    X = gdsl_list_alloc ("X", symbol_alloc, symbol_free); /* strings_compare */
    V = gdsl_list_alloc ("V", symbol_alloc, symbol_free); /* strings_compare */
    G = gdsl_list_alloc ("G", rule_alloc, rule_free);     /* symbols_compare */
    
    /* Inserting '|' & '#' into X */
    gdsl_list_insert_head (X, "|");     
    gdsl_list_insert_head (X, "#");
    
    /* Input file parsing */
    if (yy_parse_file (input_file) != 0)
    {
	printf ("Input file is not supported.\n");
	exit (EXIT_FAILURE);
    }
    
    /* Building Chomsky normal form */
    build_chomsky_normal_form (output_file);

    /* Playing with CYK algorithm */
    {
	char word[256];
	bool done = false;
	do
	{
	    printf ("Enter a word to check if it belongs to language L(G), generated by input grammar G ('quit' to exit): ");
	    scanf ("%s", word);
	    
	    done = strcmp (word, "quit") == 0 ? true : false;
	    if (done) break;

	    /* Check if entry belongs or not to the language */
	    if (CYK (word)) printf ("The word '%s' belongs ", word);
	    else printf ("The word '%s' DOES NOT belongs ", word);
	    printf ("to L(G).\n");
	    
	} while (!done);
    }
    
    /* Cleanup */
    gdsl_list_free (X);
    gdsl_list_free (V);
    gdsl_list_free (G);
    
    if (T != NULL)
    {
	gdsl_2darray_free (T);
    }
    
    if (input_file)
    {
	fclose (input_file);
    }

    if (output_file)
    {
	fclose (output_file);
    }
    
    exit (EXIT_SUCCESS);
}

