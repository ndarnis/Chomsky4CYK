static void grammar_write (FILE* file)
{
    bool new_line = true;
    gdsl_list_write (G, rule_write, (file == NULL) ? stdout : file, (void*) &new_line);
}

static void grammar_number (void)
{
    unsigned long int n = 0;
    
    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
    {
	rule* r = (rule*) gdsl_list_cursor_get_content (cg);
	rule_set_num (r, ++n);
    }
    
    gdsl_list_cursor_free (cg);
}

static void variables_number (void)
{
    unsigned long int n = 0;
    
    gdsl_list_cursor_t cv = gdsl_list_cursor_alloc (V);
    for (gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
    {
	symbol* s = (symbol*) gdsl_list_cursor_get_content (cv);
	symbol_set_num (s, ++n);
    }
    
    gdsl_list_cursor_free (cv);
}

static void build_requirements_table (void)
{
    gdsl_list_cursor_t cv = NULL, cg = NULL;
    gdsl_list_t usable_objects = gdsl_list_alloc ("UO", NULL, NULL);
    gdsl_list_t processed_objects = gdsl_list_alloc ("TO", NULL, NULL);
    unsigned long int i = 0;
    unsigned long int nb_rules = gdsl_list_get_size (G);
    unsigned long int nb_variables = gdsl_list_get_size (V);
    unsigned long int n = 1 + nb_rules + nb_variables;
    symbol* X;
    rule* P;
    
    /**********************************************************************************/
    /* RequierementsTable & usable_objects initialisations                            */
    /**********************************************************************************/
    
    grammar_number ();
    variables_number ();
    build_dependency_table ();
    
#ifdef DEBUG
    {
	bool new_line = false;
	printf ("*******************************************\n");
	gdsl_list_dump (G, rule_write, stdout, &new_line);
	printf ("*******************************************\n");
    }
#endif
    
    RequierementsTable = (int*) malloc (n * sizeof (int));
    
    /* RequierementsTable array init by variables... */
    cv = gdsl_list_cursor_alloc (V);
    for (i = 0, gdsl_list_cursor_move_to_head (cv); (X = (symbol*) gdsl_list_cursor_get_content (cv)); gdsl_list_cursor_step_forward (cv))
    {
	/* WARNING: HERE, WE MUST ABSOLUTELY HAVE i == champ num de gdsl_list_cursor_get_content (cursor) */
	assert (++i == symbol_get_num (X)); 
	RequierementsTable[i] = 1; 
    }
    gdsl_list_cursor_free (cv);
    
    /* ...then, by rules */
    cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); (P = (rule*) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	int lg = rule_get_right_member_length (P);
	
	/* WARNING: HERE, WE MUST ABSOLUTELY HAVE i == r->num + nb_variables */
	assert (++i == nb_variables + rule_get_num (P));
	RequierementsTable[i] = lg;
	
	if (lg <= 0)
	{
	    object* o = ObjectsTable[i];
	    gdsl_list_insert_tail (usable_objects, (void*) o);
	}
    }
    gdsl_list_cursor_free (cg);
    
#ifdef DEBUG
    gdsl_list_dump (usable_objects, NULL, stdout, NULL);
#endif
    
    /**********************************************************************************/
    /* RequierementsTable building algorithm                                          */
    /**********************************************************************************/
    
    while (!gdsl_list_is_empty (usable_objects))
    {
	object* alpha;
	gdsl_list_t lalpha;
	
	alpha = (object*) gdsl_list_get_head (usable_objects);
	
	lalpha = object_get_list (alpha);
	
	gdsl_list_delete_head (usable_objects);
	
	if (!gdsl_list_search (processed_objects, NULL, alpha))
	{
	    unsigned long int* k;
	    gdsl_list_insert_head (processed_objects, alpha);
	    
	    gdsl_list_cursor_t ca = gdsl_list_cursor_alloc (lalpha);
	    for (gdsl_list_cursor_move_to_head (ca); (k = gdsl_list_cursor_get_content (ca)); gdsl_list_cursor_step_forward (ca))
	    {
		unsigned long int K = *k;
		
		switch (object_get_type (alpha))
		{
		case OT_RULE:
		{
		    object* beta = ObjectsTable[K];
		    RequierementsTable[object_get_num (beta)] = RequierementsTable[object_get_num (beta)] - 1;
		    
		    if (RequierementsTable[object_get_num (beta)] <= 0)
		    {
			gdsl_list_insert_tail (usable_objects, beta);
		    }
		}
		break;
		
		case OT_VARIABLE:
		{
		    rule* r;
		    object* beta;
		    
		    /*assert (K <= gdsl_list_get_size (G));*/
		    assert (*k <= gdsl_list_get_size (G));
		    
		    r = (rule*) gdsl_list_search_by_position (G, K - 1);
		    assert (r != NULL); /* Can't be NULL ! */
		    
		    beta = ObjectsTable[rule_get_num (r) + nb_variables];
		    RequierementsTable[object_get_num (beta) + nb_variables] = RequierementsTable[object_get_num (beta) + nb_variables] - 1;
		    
		    if (RequierementsTable[object_get_num (beta) + nb_variables] <= 0)
		    {
			gdsl_list_insert_tail (usable_objects, beta);
		    }
		}
		break;
		}
	    }
	    gdsl_list_cursor_free (ca);
	}
    }
    
    /**********************************************************************************/
    /* END                                                                            */
    /**********************************************************************************/
    
    destroy_dependency_table ();
    gdsl_list_free (usable_objects);
    gdsl_list_free (processed_objects);
}

static void destroy_requirements_table (void)
{
    if (RequierementsTable != NULL)
    {
	free (RequierementsTable);
    }
}

static void build_dependency_table (void)
{
    gdsl_list_cursor_t cv, cg;
    unsigned long int nb_variables = gdsl_list_get_size (V);
    unsigned long int nb_rules = gdsl_list_get_size (G);
    unsigned long int n = 1 + nb_rules + nb_variables;
    unsigned long int i = 0;
    
    ObjectsTable = (object**) malloc (n * sizeof (object*));
    
    /* Variables */
    cv = gdsl_list_cursor_alloc (V);
    for (gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
    {
	symbol*s = (symbol*) gdsl_list_cursor_get_content (cv);
	object* o = object_alloc (OT_VARIABLE, (void*) s);
	gdsl_list_t lo = object_get_list (o);
	
	assert (++i == symbol_get_num (s));
	
	gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
	for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
	{
	    rule* r = (rule*) gdsl_list_cursor_get_content (cg);
	    gdsl_list_t ls = rule_get_production (r);
	    gdsl_list_cursor_t cls = gdsl_list_cursor_alloc (ls);
	    for (gdsl_list_cursor_move_to_head (cls); gdsl_list_cursor_get_content (cls); gdsl_list_cursor_step_forward (cls))
	    {
		symbol* sr = (symbol*) gdsl_list_cursor_get_content (cls);
		unsigned long int k = rule_get_num (r);
		
		if (symbol_names_compare (sr, s) == 0)
		{
		    gdsl_list_insert_tail (lo, (void*) &k);
		}
	    }
	    gdsl_list_cursor_free (cls);
	}
	gdsl_list_cursor_free (cg);
	
	ObjectsTable[i] = o;
    }
    gdsl_list_cursor_free (cv);
    
    /* Rules */
    cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
    {
	rule* r = (rule*) gdsl_list_cursor_get_content (cg);
	object* o = object_alloc (OT_RULE, (void*) r);
	gdsl_list_t lo = object_get_list (o);
	symbol* s = rule_get_symbol (r);
	unsigned long int k = symbol_get_num (s);
	
	assert (++i == nb_variables + rule_get_num (r));
	
	if (symbol_is_variable (s))
	{
	    gdsl_list_insert_tail (lo, (void*) &k);
	}
	
	ObjectsTable[i] = o;
    }
    gdsl_list_cursor_free (cg);
}

static void destroy_dependency_table (void)
{
    unsigned long int i;
    unsigned long int n = 1 + gdsl_list_get_size (G) + gdsl_list_get_size (V);
    
    for (i = 1; i < n; i++)
    {
	object_free (ObjectsTable[i]);
    }
    
    free (ObjectsTable);
}

/* Main algorithm: building of Chomsky normal form */

static void build_chomsky_normal_form (FILE* out)
{
    if (verbose)
    {
	printf ("INPUT GRAMMAR G:\n");
	grammar_write (stdout);
	printf ("\n");
    }
       
    Step1 ();
    Step2 ();
    Step3 ();
    Step4 ();
    Step5 ();
    
    if (verbose)
    {
	printf ("\nGRAMMAR G IN CHOMSKY NORMAL FORM:\n");
	grammar_number ();
	grammar_write (stdout);
	printf ("\n");
    }

    if (out)
    {
	grammar_write (out);
    }
}

/******************************************************************************/
/* STEP 1: Union removal                                                      */
/******************************************************************************/

static void Step1 (void)
{
    rule* r;
    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
    
    /* For each rule r, we check its production part p */
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule*) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	symbol* sp;
	gdsl_list_t p = rule_get_production (r); /* p is r's production */
	
	/* For each p's symbol (sp), we check if its union */
	gdsl_list_cursor_t cp = gdsl_list_cursor_alloc (p);
	gdsl_list_cursor_move_to_head (cp);
	while ((sp = (symbol *) gdsl_list_cursor_get_content (cp))) /* sp is p's symbol */
	{
	    if (symbol_is_union (sp))
	    {
		symbol* sg;
		rule* tmp = (rule*) gdsl_list_cursor_insert_after (cg, (void*) rule_get_symbol (r));
		gdsl_list_t l = rule_get_production (tmp);

		gdsl_list_cursor_delete (cp); /* NOTE 1: WARNING: curor is moved AFTER deleted element !!!
                                               * So, we *MUST NOT* call gdsl_list_cursor_step_forward (cp);
					       * (check GDSL's manual).
					       */

		while ((sg = (symbol *) gdsl_list_cursor_get_content (cp)) && !symbol_is_union (sg))
		{
		    gdsl_list_insert_tail (l, sg);
		    gdsl_list_cursor_delete (cp);
		    /* FORBIDDEN: gdsl_list_cursor_step_forward (cp); cf. NOTE 1 */
		}
	    }
	    else
	    {
		/* Here it's okay because we have not deleted cursor, cf. NOTE 1 */
		gdsl_list_cursor_step_forward (cp);
	    }
	}
	gdsl_list_cursor_free (cp);
    }
    gdsl_list_cursor_free (cg);

#ifdef DEBUG
    if (verbose)
    {
	printf ("****** STEP 1 ******\n");
	grammar_write (stdout);
	printf ("*********************\n");
    }
#endif
}

/*************************************************************************************************************************/
/* STEP 2: Transformation du membre droit de chaque règle en une lettre ou en une concaténation de non terminaux         */
/*************************************************************************************************************************/

static void Step2 (void)
{
    rule *r;
    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
    
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule *) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	gdsl_list_cursor_t cp = NULL;
	gdsl_list_t prod = rule_get_production (r);
	symbol *sp;
	symbol *sr = rule_get_symbol (r);
	char *symbol_name = symbol_get_name (sr);
	
	if (symbol_name[1] == '_') continue;
	
	cp = gdsl_list_cursor_alloc (prod);
	for (gdsl_list_cursor_move_to_head (cp); (sp = (symbol *) gdsl_list_cursor_get_content (cp)); gdsl_list_cursor_step_forward (cp))
	{
	    if (symbol_is_terminal (sp))
	    {
		symbol *s;
		char *chaine; 
		int bytes_nb = 3 + strlen (symbol_get_name (sp));
		
		chaine = (char *) malloc (bytes_nb);
		snprintf (chaine, bytes_nb, "V_%s", symbol_get_name (sp));
		
		if (!(s = (symbol *) gdsl_list_search (V, strings_compare, (void *) chaine)))
		{
		    gdsl_list_t l;
		    rule *tmp;
		    s = (symbol*) gdsl_list_insert_tail (V, (void*) chaine);
		    tmp = (rule*) gdsl_list_insert_tail (G, s);
		    l = rule_get_production (tmp);
		    gdsl_list_insert_tail (l, (void*) sp); 
		}
		gdsl_list_cursor_set_content (cp, s);
		free (chaine);
	    }
	}
	gdsl_list_cursor_free (cp);
    }
    gdsl_list_cursor_free (cg);

#ifdef DEBUG
    if (verbose)
    {
	printf ("\n****** STEP 2 ******\n");
	grammar_write (stdout);
	printf ("*********************\n");
    }
#endif
}

/*************************************************************************************************************************/
/* STEP 3: Removing of too-long right members (who have length > 2)                                                      */
/*************************************************************************************************************************/

static void Step3 (void)
{
    int i = 1;
    rule *r;
    
    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule *) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	gdsl_list_t prod = rule_get_production (r);
        gdsl_list_cursor_t cp = NULL;
	
	if (gdsl_list_get_size (prod) <= 2) continue;

	cp = gdsl_list_cursor_alloc (prod);
	for (gdsl_list_cursor_move_to_head (cp), gdsl_list_cursor_step_forward (cp); gdsl_list_cursor_get_content (cp); gdsl_list_cursor_step_forward (cp))
	{
	    if (gdsl_list_cursor_has_succ (cp))
	    {
	      gdsl_list_t l; 
	      rule *tmp;
	      symbol *s;
	      char *chaine;
	      void *x;

	      chaine = (char *) malloc (5); 
	      snprintf (chaine, 5, "N_%02d", i++);
	      s = (symbol *) gdsl_list_insert_tail (V, (void *) chaine);
	      free (chaine);
	      
	      tmp = (rule *) gdsl_list_cursor_insert_after (cg, (void *) s);
	      l = rule_get_production (tmp);
	      
	      while ((x = gdsl_list_cursor_get_content (cp)))
	      {		  
		  gdsl_list_insert_tail (l, (void *) x);
		  gdsl_list_cursor_delete (cp);
		  /*gdsl_list_cursor_step_forward (cp); cf. NOTE 1 */
	      }

	      gdsl_list_insert_tail (prod, (void *) gdsl_list_get_tail (V));
	    }
 	}
	gdsl_list_cursor_free (cp);
    }
    gdsl_list_cursor_free (cg);

#ifdef DEBUB
  if (verbose)
    {
      printf ("\n****** STEP 3 ******\n");
      grammar_write (stdout);
      printf ( "*********************\n");
    }
  #endif
}

/*************************************************************************************************************************/
/* STEP 4: elimination of the maximum number of empty words.                                                             */
/*************************************************************************************************************************/

static void Step4 (void)
{
    rule *r;
    rule *rg;
    char *axiome = symbol_get_name (GetAxiom ()); /* WARNING: DO NOT MOVE ! */
    symbol *x;
    gdsl_list_cursor_t cv = NULL;
    gdsl_list_cursor_t cg = NULL;
    
    /* a) Ajout des nouveaux symboles non-terminaux X~ et X# à V et introduction des nouvelles règles X -> X~ et X -> X# dans G */
    cv = gdsl_list_cursor_alloc (V);
    cg = gdsl_list_cursor_alloc (G);
    
    for (gdsl_list_cursor_move_to_tail (cg), gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
    { 
	gdsl_list_t actu;
	symbol *v;
	symbol *symb = (symbol *) gdsl_list_cursor_get_content (cv);
	char *chaine;
	
	chaine = (char *) malloc (2 + strlen (symbol_get_name (symb)));
	sprintf (chaine, "%s%c", symbol_get_name (symb), SYMB_PLUS);
	
	v = (symbol *) gdsl_list_insert_head (V, (void *) chaine);
	r = (rule *)gdsl_list_insert_tail (G, (void *) symb);
	actu = rule_get_production (r);
	gdsl_list_insert_head (actu, v);
	free (chaine);
	
	chaine = (char *) malloc (2 + strlen (symbol_get_name (symb))); 
	sprintf (chaine, "%s%c", symbol_get_name (symb), SYMB_EPSILON);
	
	v = (symbol *) gdsl_list_insert_head (V, chaine);
	r = (rule *) gdsl_list_insert_tail (G, (void *) symb);
	actu = rule_get_production (r);
	gdsl_list_insert_head (actu, v);
	free (chaine);
    }

#ifdef DEBUG
    if (verbose)
    {
	printf ("\n****** STEP 4 ******\n");
	printf ("a)\n");
	grammar_write (stdout);
    }
#endif
    
    /* b) Rules modifications */
    for ( ; (rg = (rule*) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_backward (cg))
    {
	symbol* rs = rule_get_symbol (rg);
	symbol* symb = NULL;
	char* chaine = (char *) symbol_get_name (rs);
	gdsl_list_t actu = rule_get_production (rg);
	gdsl_list_cursor_t ca = gdsl_list_cursor_alloc (actu);

	symb = (symbol*) gdsl_list_cursor_get_content (ca);
	gdsl_list_cursor_move_to_head (ca);
	
	/* Modification of kind X -> c : X~ -> c */
	if (symbol_is_terminal (symb)) 
	{
	    char* mot = (char*) malloc (2 + strlen (chaine));
	    sprintf (mot, "%s%c", chaine, SYMB_PLUS);	  
	    rule_set_symbol (rg, (symbol*) gdsl_list_search (V, strings_compare, (void*) mot));
	    free (mot);
	    continue;
	}

	/* Modification of kind X -> # : X# -> # */
	if (symbol_is_epsilon (symb)) 
	{
	    char* mot = (char*) malloc (2 + strlen (chaine));
	    sprintf (mot, "%s%c", chaine, SYMB_EPSILON);
	    rule_set_symbol (rg, gdsl_list_search (V, strings_compare, (void*) mot));

	    free (mot);
	    continue;
	}

	/* Modification of kind X -> Y : X~ -> Y~ and X# -> Y# */
	if (!gdsl_list_cursor_has_succ (ca)) 
	{		  
	    symbol *vc1, *vc2;
	    char *mot1, *mot2;
	    gdsl_list_t actu2;

	    mot1 = (char *) malloc (2 + strlen (chaine)); 
	    sprintf (mot1, "%s%c", chaine, SYMB_PLUS); 
	    mot2 = (char *) malloc (2 + strlen (symbol_get_name (symb))); 
	    sprintf (mot2, "%s%c", symbol_get_name (symb), SYMB_PLUS); 
	    
	    if ((vc1 = (symbol *) gdsl_list_search (V, strings_compare, (void *) mot1)))
	    {
		rule_set_symbol (rg, vc1);
	    }
	    
	    if ((vc2 = (symbol *) gdsl_list_search (V, strings_compare, (void *) mot2)))
	    {
		gdsl_list_cursor_set_content (ca, vc2);
	    }
	    
	    free (mot1);
	    free (mot2);
	    
	    mot1 = (char *) malloc (2 + strlen (chaine)); 
	    sprintf (mot1, "%s#", chaine); 
	    mot2 = (char *) malloc (2 + strlen (symbol_get_name (symb))); 
	    sprintf (mot2, "%s#", symbol_get_name (symb)); 
	    
	    if ((vc1 = gdsl_list_search (V, strings_compare, (void *) mot1)))
	    {
		r = (rule *) gdsl_list_cursor_insert_after (cg, vc1);
		actu2 = rule_get_production (r);
	    }
	    
	    if ((vc2 = gdsl_list_search (V, strings_compare, (void *) mot2)))
		gdsl_list_insert_tail (actu2, vc2);
	    
	    continue;
	}

	/* Modification of kind X -> Y Z : X~ -> Y~ Z~, X~ -> Y~ Z#, X~ -> Y# Z~ and X# -> Y# Z# */
	{
	    symbol *vc, *vc0, *vc1, *vc2;
	    char *mot1, *mot2;
	    symbol *as;
	    rule *cg2, *cg3, *cg4;
	    gdsl_list_t actu2, actu3, actu4;
	    
	    mot1 = (char *) malloc (2 + strlen (chaine)); 
	    sprintf( mot1, "%s%c", chaine, SYMB_PLUS); 
	    mot2 = (char *) malloc (2 + strlen (chaine)); 
	    sprintf (mot2, "%s%c", chaine, SYMB_EPSILON); 
	    
	    if ((vc = (symbol *) gdsl_list_search (V, strings_compare, (void *) mot1)))
	    {
		rule_set_symbol (rg, vc);
	    }
	    
	    vc0 = (symbol *) gdsl_list_search (V, strings_compare, (void *) mot2);
	    
	    /* Insertion des 3 NT dans G avec X qui donne X~ X~ X# */
	    cg2 = (rule *) gdsl_list_cursor_insert_after (cg, (void *) vc); 
	    actu2 = rule_get_production (cg2);
	    
	    cg3 = (rule *) gdsl_list_cursor_insert_after (cg, (void *) vc); 
	    actu3 = rule_get_production (cg3);
	    
	    cg4 = (rule *)gdsl_list_cursor_insert_after (cg, (void *) vc0); 
	    actu4 = rule_get_production (cg4);
	    
	    free (mot1);
	    free (mot2);
	    
	    /* Update of first element into the 4 lists */
	    mot1 = (char *) malloc (2 + strlen (symbol_get_name (symb)));
	    mot2 = (char *) malloc (2 + strlen (symbol_get_name (symb)));
	    sprintf (mot1, "%s%c", symbol_get_name (symb), SYMB_PLUS); 
	    sprintf (mot2, "%s%c", symbol_get_name (symb), SYMB_EPSILON); 
	    vc1 = gdsl_list_search (V, strings_compare, (void *) mot1);
	    vc2 = gdsl_list_search (V, strings_compare, (void *) mot2);
	    
	    gdsl_list_cursor_set_content (ca, vc1);
	    gdsl_list_insert_tail (actu2, vc1);
	    gdsl_list_insert_tail (actu3, vc2);
	    gdsl_list_insert_tail (actu4, vc2);
	    gdsl_list_cursor_step_forward (ca);
	    
	    free (mot1);
	    free (mot2);
	    
	    /* Update of second element into the 4 lists */
	    as = (symbol *) gdsl_list_cursor_get_content (ca);
	    mot1 = (char *) malloc (2 + strlen (symbol_get_name (symb)));
	    mot2 = (char *) malloc (2 + strlen (symbol_get_name (symb))); 
	    
	    sprintf (mot1, "%s%c", symbol_get_name (as), SYMB_PLUS ); 
	    sprintf (mot2, "%s%c", symbol_get_name (as), SYMB_EPSILON); 
	    
	    vc1 = (symbol *) gdsl_list_search ( V, strings_compare, (void *) mot1);
	    vc2 = (symbol *) gdsl_list_search ( V, strings_compare, (void *) mot2);
	    
	    gdsl_list_cursor_set_content (ca, (void *) vc1);
	    gdsl_list_insert_tail (actu2, (void *) vc2);
	    gdsl_list_insert_tail (actu3, (void *) vc1);
	    gdsl_list_insert_tail (actu4, (void *) vc2); 
	    
	    free (mot1);
	    free (mot2); 
	}
	gdsl_list_cursor_free (ca);
    }

#ifdef DEBUG
    if (verbose)
    {
	printf ("b)\n");
	grammar_write (stdout);
    }
#endif
    
    /* c) Removing of initials variables X except axiom */
    gdsl_list_cursor_move_to_head (cg);
    while ( (r = (rule *) gdsl_list_cursor_get_content (cg)) /*!gdsl_list_cursor_is_on_tail (cg)*/)
    {
	symbol *s = rule_get_symbol (r);
	char *ns = NULL;
	int lg = strlen (axiome);

	ns = symbol_get_name (s);

	/* We do not process axiom */
	if (strncmp (axiome, ns, lg) == 0)
	{
	    gdsl_list_cursor_step_forward (cg);
	    continue;
	}

	/* Symbol s is not initial variable */
	if (!symbol_is_initial (s))
	{
	    gdsl_list_cursor_step_forward (cg);
	    continue;
	}

	/* Symbol s IS an initial variabl, so it must be removed */
	gdsl_list_cursor_delete (cg); /* cf. NOTE 1 */
    }

    /* Removing useless variables into V */
    remove_useless_variables ();

#ifdef DEBUG
    if (verbose)
    {
	printf ("c)\n");
	grammar_write (stdout);
    }
#endif
    
    /* d) */
    build_requirements_table ();

    for (gdsl_list_cursor_move_to_head (cv); (x = (symbol *) gdsl_list_cursor_get_content (cv)); gdsl_list_cursor_step_forward (cv))
    {
	symbol *X0;
	char *symbol_name = symbol_get_name (x);
	unsigned long int n = strlen (symbol_name);
	
	if (symbol_name[n-1] != '#')
	{
	    continue;
	}
	
	X0 = gdsl_list_search (V, strings_compare, (char*) symbol_name);
	
	switch (L (X0))
	{
	case LG_EMPTY:
	{
	    rule *r;
	    
	    gdsl_list_cursor_move_to_head (cg);
	    while ((r = (rule *) gdsl_list_cursor_get_content (cg)))
	    {
		gdsl_list_t l = rule_get_production (r);
		symbol *s1, *s2 = NULL;
		
		s1 = (symbol *) gdsl_list_get_head (l);
		
		if (gdsl_list_get_size (l) == 2)
		{
		    s2 = (symbol *) gdsl_list_get_tail (l);
		}
		
		if (symbol_names_compare (X0, s1) == 0)
		{
		    gdsl_list_cursor_delete (cg); /* cf. NOTE 1 */
		    continue;
		}
		
		if (s2 != NULL)
		{
		    if (symbol_names_compare (X0, s2) == 0)
		    {
			gdsl_list_cursor_delete (cg);  /* cf. NOTE 1 */
			continue;
		    }
		}
		
		gdsl_list_cursor_step_forward (cg);
	    }
	}
	break;
	
	case LG_EPSILON:
	{
	    rule* r;
	    
	    gdsl_list_cursor_move_to_head (cg);
	    while ((r = (rule*) gdsl_list_cursor_get_content (cg)))
	    {
		gdsl_list_t l = rule_get_production (r);
		symbol* s1 = (symbol*) gdsl_list_get_head (l);
		symbol* s2 = NULL;
		char* symbol_name = symbol_get_name (s1);
		unsigned long int n = strlen (symbol_name);
		
		if (gdsl_list_get_size (l) == 1)
		{
		    if (symbol_name[n-1] == '#')
		    {
			symbol* epsilon = (symbol*) gdsl_list_search (X, strings_compare, (void *) "#");
			gdsl_list_delete_head (l);
			gdsl_list_insert_head (l, (void *) epsilon);
			gdsl_list_cursor_step_forward (cg);
			continue;
		    }
		    else
		    {
			if (symbol_names_compare (X0, s1) == 0)
			{
			    gdsl_list_cursor_delete (cg); /* cf. NOTE 1 */
			    continue;
			}
		    }
		}
		else
		{
		    s2 = (symbol*) gdsl_list_get_tail (l);
		    
		    if (symbol_names_compare (X0, s1) == 0)
		    {
			gdsl_list_delete_head (l);
		    }
		    
		    if (symbol_names_compare (X0, s2) == 0)
		    {
			gdsl_list_delete_tail (l);
		    }
		    
		    if (gdsl_list_get_size (l) == 0)
		    {
			gdsl_list_cursor_delete (cg); /* cf. NOTE 1 */
			continue;
		    }
		}

		gdsl_list_cursor_step_forward (cg);
	    }
	}
	break;
	}
    }
    
    /* Removing of rules of kind X# -> ... left */
    gdsl_list_cursor_move_to_head (cg);
    while ((r = (rule *) gdsl_list_cursor_get_content (cg)))
    {
	symbol* s = rule_get_symbol (r);
	char* symbol_name = symbol_get_name (s);
	unsigned long int n = strlen (symbol_name);
	
	if (symbol_name[n-1] == SYMB_EPSILON)
	{
	    gdsl_list_cursor_delete (cg);  /* cf. NOTE 1 */
	    continue;
	}
	
	gdsl_list_cursor_step_forward (cg);
    }
    
    destroy_requirements_table ();
    
    /* Removing of useless non-terminal from V */
    remove_useless_variables ();
    
    gdsl_list_cursor_free (cv);
    gdsl_list_cursor_free (cg);

#ifdef DEBUG
    if (verbose)
    {
	printf ("d)\n");
	grammar_number ();
	grammar_write (stdout);
	printf ("*********************\n");
    }
#endif
}

