/* STEP 5: Removing unitary rules                                                                                        */
/*************************************************************************************************************************/

static void Step5 (void)
{
    gdsl_list_cursor_t cg = NULL;
    gdsl_list_t tmp0, tmp1, tmp2;
    rule* r;
    
    tmp0 = gdsl_list_alloc (NULL, NULL, NULL);
    tmp1 = gdsl_list_alloc (NULL, NULL, NULL);
    tmp2 = gdsl_list_alloc (NULL, NULL, NULL);
    
    grammar_number ();
    variables_number ();
    
    /* Build of T, the transitive closure of graph belonging to relation -> */
    transitive_closure ();

    /* 1) For each rule X -> c */
    cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule*) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	symbol* c;
	symbol* X = rule_get_symbol (r);
	gdsl_list_t l = rule_get_production (r);
	gdsl_list_cursor_t cv = NULL;
	
	if (gdsl_list_get_size (l) != 1)
	{
	    continue;
	}
	
	c = (symbol*) gdsl_list_get_head (l);
	if (!c)
	{
	    continue;
	}
	
	if (!symbol_is_terminal (c))
	{
	    continue;
	}
	
	/* We've got a rule X -> c */
	cv = gdsl_list_cursor_alloc (V);
	for (gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
	{
	    symbol* X0 = (symbol*) gdsl_list_cursor_get_content (cv);
	    
	    if (leads_to (X0, X) && symbol_get_num (X0) != symbol_get_num (X)) /* Adding of rule X0 -> c into G */
	    {
		rule* tmp = (rule*) gdsl_list_cursor_insert_before (cg, (void*) X0);
		gdsl_list_t ltmp = rule_get_production (tmp);
	      gdsl_list_insert_tail (ltmp, (void*) c);
	    }
	}
	gdsl_list_cursor_free (cv);
    }
    
    /* 2) For each rule X -> YZ */
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule*) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	gdsl_list_t l = rule_get_production (r);
	symbol* X = rule_get_symbol (r);
	symbol* Y;
	symbol* Z;
	
	if (gdsl_list_get_size (l) == 2) /* We've got a rule X -> YZ */
	{
	    gdsl_list_cursor_t ct0, cv = gdsl_list_cursor_alloc (V);
	    
	    Y = (symbol*) gdsl_list_get_head (l);
	    Z = (symbol*) gdsl_list_get_tail (l);
	    
	    for (gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
	    {
	      symbol* X0 = (symbol*) gdsl_list_cursor_get_content (cv);
	      
	      if (leads_to (X0, X)) gdsl_list_insert_tail (tmp0, (void*) X0);
	      if (leads_to (Y, X0)) gdsl_list_insert_tail (tmp1, (void*) X0);
	      if (leads_to (Z, X0)) gdsl_list_insert_tail (tmp2, (void*) X0 );
	    }

	    /* Produit cartésien des listes tmp0, tmp1, tmp2 */
	    ct0 = gdsl_list_cursor_alloc (tmp0);
	    for (gdsl_list_cursor_move_to_head (ct0); gdsl_list_cursor_get_content (ct0); gdsl_list_cursor_step_forward (ct0))
	    {
		gdsl_list_cursor_t ct1 = gdsl_list_cursor_alloc (tmp1);
		for (gdsl_list_cursor_move_to_head (ct1); gdsl_list_cursor_get_content (ct1); gdsl_list_cursor_step_forward (ct1))
		{
		    gdsl_list_cursor_t ct2 = gdsl_list_cursor_alloc (tmp2);
		    for (gdsl_list_cursor_move_to_head (ct2 ); gdsl_list_cursor_get_content (ct2); gdsl_list_cursor_step_forward (ct2))
		    {
		      symbol* s0 = (symbol*) gdsl_list_cursor_get_content (ct0);
		      symbol* s1 = (symbol*) gdsl_list_cursor_get_content (ct1);
		      symbol* s2 = (symbol*) gdsl_list_cursor_get_content (ct2);
		      rule* r0;
		      gdsl_list_t l0;
		      
		      if (symbol_names_compare (X, s0) == 0 && symbol_names_compare (Y, s1) == 0 && symbol_names_compare (Z, s2) == 0)
		      {
			  continue; /* Avoid of adding rule X -> YZ twice */
		      }

		      r0 = (rule *) gdsl_list_cursor_insert_after (cg, (void*) s0);
		      gdsl_list_cursor_step_forward (cg);
		      l0 = rule_get_production (r0);
		      gdsl_list_insert_tail (l0, (void*) s1);
		      gdsl_list_insert_tail (l0, (void*) s2);
		    }
		    gdsl_list_cursor_free (ct2);
		}
		gdsl_list_cursor_free (ct1);
	    }
	    gdsl_list_cursor_free (ct0);
	    gdsl_list_cursor_free (cv);
	    
	  gdsl_list_flush (tmp0);
	  gdsl_list_flush (tmp1);
	  gdsl_list_flush (tmp2);
	}
    }

    /* 3) Removing of unitary rules */
    gdsl_list_cursor_move_to_head (cg);
    while ((r = (rule *) gdsl_list_cursor_get_content (cg)))
    {
	gdsl_list_t l = rule_get_production (r);
	symbol* Y;

	if (gdsl_list_get_size (l) != 1)
	{
	    gdsl_list_cursor_step_forward (cg);
	    continue;
	}
	
	Y = (symbol*) gdsl_list_get_head (l);
	if (!symbol_is_variable (Y))
	{
	    gdsl_list_cursor_step_forward (cg);
	    continue;
	}
	
	gdsl_list_cursor_delete (cg); /* cf. NOTE 1 */
    }
    
    gdsl_list_cursor_free (cg);
    
    gdsl_list_free (tmp0);
    gdsl_list_free (tmp1);
    gdsl_list_free (tmp2);
}

static symbol* GetAxiom (void)
{
    Axiom = (symbol*) gdsl_list_get_head (V);
    return Axiom;
}

static unsigned short int L (symbol* s)
{
    unsigned long int n = symbol_get_num (s);
    return (RequierementsTable[n] == 0) ? LG_EPSILON : LG_EMPTY;
}  

/* CYK Algorithm */

static bool CYK (char* word)
{
    bool result = false;
    int False = false, True = true;
    int i, j, k, n;
    unsigned long int card_v;
    gdsl_2darray_t* M;
    gdsl_list_cursor_t cv;
    
    grammar_number ();
    variables_number ();
    
    /* First, we check if all w_i belongs to X */
    n = strlen (word);
    for (i = 0; i < n; i++)
    {
	char c[2];
	c[0] = word[i];
	c[1] = '\0';
	
	if (gdsl_list_search (X, strings_compare, (void*) c) == NULL)
	{
	    if (verbose)
	    {
		printf ("*** Error: the %d%s letter ('%c') of input word '%s' is *NOT* defined into X set definition of input grammar G.\n", i+1, i+1==1?"-st":"-th", word[i], word);
	    }
	    
	    return false;
	}
    }
    
    card_v = gdsl_list_get_size (V);
    M = (gdsl_2darray_t*) malloc ((1 + n) * sizeof (gdsl_2darray_t));
    for (i = 1; i <= n; i++) M[i] = gdsl_2darray_alloc (NULL, n + 1, card_v + 1, number_alloc, number_free);
    
    /* Initialisation of matrix M */
    cv = gdsl_list_cursor_alloc (V);
    for (gdsl_list_cursor_move_to_head (cv); gdsl_list_cursor_get_content (cv); gdsl_list_cursor_step_forward (cv))
    {
	symbol* X = (symbol*) gdsl_list_cursor_get_content (cv);
	
	for (i = 1; i <= n; i++)
	{
	    for (k = i; k <= n; k++)
	    {
		gdsl_2darray_set_content (M[i], k, symbol_get_num (X), (void *) &False);
	    }
	}
	
	for (i = 1; i <= n; i++)
	{
	    bool found = false;
	    char c = word[i-1]; /* c = word_i_i */
	    
	    /* We're searching for a rule of the form X -> c into G */
	    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
	    for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
	    {
		rule* r = (rule*) gdsl_list_cursor_get_content (cg);
		gdsl_list_t l;
		symbol *C, *sr = rule_get_symbol (r);
		char* nom_c;
		
		if (symbol_names_compare (X, sr) != 0) continue;
		
		l = rule_get_production (r);
		if (gdsl_list_get_size (l) != 1) continue;
		
		C = (symbol*) gdsl_list_get_head (l);
		nom_c = symbol_get_name (C);
		if (strlen (nom_c) != 1) continue;
		
		if (c == nom_c[0])
		{
		    found = true;
		    break;
		}
	    }
	    gdsl_list_cursor_free (cg);
	    
	    if (found)
	    {
		gdsl_2darray_set_content (M[i], i, symbol_get_num (X), (void*) &True);
	    }
	}
    }

    /*************************************************************/
    /* CYK ALGORITHM                                             */
    /*************************************************************/
    
    for (k = 2; k <= n; k++)
    {
	for (i = k - 1; i > 0; i--)
	{
	    /* For each rule of kind X -> Y Z */
	    gdsl_list_cursor_t cg = gdsl_list_cursor_alloc (G);
	    for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
	    {
		rule* r = (rule*) gdsl_list_cursor_get_content (cg);
		symbol* X = rule_get_symbol (r), *Y, *Z;
		gdsl_list_t l = rule_get_production (r);
		
		if (gdsl_list_get_size (l) != 2)
		{
		    continue;
		}
		
		Y = gdsl_list_get_head (l);
		Z = gdsl_list_get_tail (l);
		
		for (j = i; j <= k - 1; j++)
		{
		    int* n1;
		    int* n2;
		    gdsl_2darray_t m1 = M[i];
		    gdsl_2darray_t m2 = M[j+1];
		    n1 = (int*) gdsl_2darray_get_content (m1, j, symbol_get_num (Y));
		    n2 = (int*) gdsl_2darray_get_content (m2, k, symbol_get_num (Z));
		    
		    if (*n1 && *n2)
		    {
			gdsl_2darray_set_content (m1, k, symbol_get_num (X), (void*) &True);
		    }
		}
	    }
	}
    }
    
    {
	int* r = (int*) gdsl_2darray_get_content (M[1], n, symbol_get_num (Axiom));
	result = (*r == 1 ? true : false);
    }
    
    for (i = 1; i <= n; i++) gdsl_2darray_free (M[i]);    
    free (M);
    
    return result;
}

static void transitive_closure (void)
{
    unsigned long int i, j, k, m = gdsl_list_get_size (V);
    int zero = 0, un = 1;
    gdsl_2darray_t M = gdsl_2darray_alloc (NULL, m+1, m+1, number_alloc, number_free);
    gdsl_list_cursor_t cg;
    
    T = gdsl_2darray_alloc (NULL, m+1, m+1, number_alloc, number_free);
    
    /* Init M et T */
    for (i = 1; i <= m; i++)
    {
	for (j = 1; j <= m; j++)
	{
	    if (i == j)
	    {
		gdsl_2darray_set_content (M, i, j, (void*) &un);
		gdsl_2darray_set_content (T, i, j, (void*) &un);
	    }
	    else
	    {
		gdsl_2darray_set_content (M, i, j, (void*) &zero);
		gdsl_2darray_set_content (T, i, j, (void*) &zero);
	    }
	}
    }
    
    /* Construction des matrices M et T à partir de la grammaire G */
    cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); gdsl_list_cursor_get_content (cg); gdsl_list_cursor_step_forward (cg))
    {
	rule* r = (rule*) gdsl_list_cursor_get_content (cg);
	gdsl_list_t l = rule_get_production (r);
	symbol* s1 = rule_get_symbol (r);
	symbol* s2;
	
	if (gdsl_list_get_size (l) != 1)
	{
	    continue;
	}
	
	s2 = (symbol*) gdsl_list_get_head (l);
	
	if (symbol_is_terminal (s2))
	{
	    continue;
	}
	
	gdsl_2darray_set_content (M, symbol_get_num (s1), symbol_get_num (s2), (void*) &un);
	gdsl_2darray_set_content (T, symbol_get_num (s1), symbol_get_num (s2), (void*) &un); 
    }
    gdsl_list_cursor_free (cg);
    
    /* Fermeture transitive (Warshall) */
    for (i = 1; i <= m; i++)
    {
	for (j = 1; j <= m; j++)
	{
	    int* z = (int*) gdsl_2darray_get_content (T, j, i);
	    
	    if (*z == 1)
	    {
		for (k = 1; k <= m; k++)
		{
		    int* a = (int*) gdsl_2darray_get_content (T, i, k);
		    if (*a == 1)
		    {
			gdsl_2darray_set_content (T, j, k, (void*) &un);
		    }
		}
	    }
	}
    }
    
    gdsl_2darray_free (M);
}

static bool leads_to (symbol* v0, symbol* v1)
{
    int* k = (int*) gdsl_2darray_get_content (T, symbol_get_num (v0), symbol_get_num (v1));
    return (*k > 0) ? true : false;
}

static void remove_useless_variables (void)
{
    symbol* s;
    gdsl_list_cursor_t cv = gdsl_list_cursor_alloc (V);
    
    gdsl_list_cursor_move_to_head (cv);
    
    while ((s = (symbol*) gdsl_list_cursor_get_content (cv)))
    {
	if (!symbol_is_in_grammar (s))
	{
	    gdsl_list_cursor_delete (cv); /* cf. NOTE 1 */
	}
	else
	{
	    gdsl_list_cursor_step_forward (cv);
	}
    }
    
    gdsl_list_cursor_free (cv);
}

static bool symbol_is_in_grammar (symbol* s)
{
    rule* r = NULL;
    gdsl_list_cursor_t cg = NULL;
    
    if (gdsl_list_search (G, symbols_compare, s) != NULL)
    {
	return true;
    }
    
    cg = gdsl_list_cursor_alloc (G);
    for (gdsl_list_cursor_move_to_head (cg); (r = (rule *) gdsl_list_cursor_get_content (cg)); gdsl_list_cursor_step_forward (cg))
    {
	gdsl_list_t ls = rule_get_production (r);
	if (gdsl_list_search (ls, strings_compare, (void *) symbol_get_name (s)) != NULL )
	{
	    gdsl_list_cursor_free (cg);
	    return true;
	}
    }
    
    gdsl_list_cursor_free (cg);
    return false;
}

